from pathlib import Path
import argparse
import math

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib import font_manager
from matplotlib.ticker import MaxNLocator
import numpy as np
import pandas as pd


PARTICIPANTS = ('A001', 'A002', 'A003')
MAX_SCORE = 36
ATTEMPTS_PER_RUN = 10


def setup_style():
    available = {font.name for font in font_manager.fontManager.ttflist}
    font = next((name for name in ('Arial', 'Liberation Sans', 'DejaVu Sans') if name in available), 'sans-serif')
    plt.rcParams.update({
        'font.family': font,
        'axes.unicode_minus': False,
        'font.size': 12,
        'axes.labelsize': 14,
        'xtick.labelsize': 11,
        'ytick.labelsize': 11,
        'legend.fontsize': 10,
    })


def load_game_runs(path):
    data = pd.read_csv(path, encoding='utf-8-sig')
    data.columns = data.columns.str.strip()
    required = {'Date', 'Session_ID', 'Block_Score'}
    if not required.issubset(data.columns):
        raise ValueError(f'{path.name}: missing columns {sorted(required - set(data.columns))}')

    data = data.dropna(how='all').reset_index(drop=True)
    data['Session_ID'] = pd.to_numeric(data['Session_ID'], errors='raise').astype(int)
    data['Block_Score'] = pd.to_numeric(data['Block_Score'], errors='raise')
    if data.empty or not data['Block_Score'].between(0, MAX_SCORE).all():
        raise ValueError(f'{path.name}: invalid or missing block scores')

    records = []
    for session_id, group in data.groupby('Session_ID', sort=True):
        if len(group) != ATTEMPTS_PER_RUN:
            raise ValueError(f'{path.name}: game run {session_id} has {len(group)} attempts')
        if group['Date'].nunique(dropna=False) != 1:
            raise ValueError(f'{path.name}: game run {session_id} has inconsistent dates')
        scores = group['Block_Score']
        mean_score = scores.mean()
        records.append({
            'Session_ID': session_id,
            'Accuracy': 100 * mean_score / MAX_SCORE,
            'CV': 100 * scores.std(ddof=1) / mean_score if mean_score > 0 else np.nan,
        })

    if not records:
        raise ValueError(f'{path.name}: no evaluable game runs')
    result = pd.DataFrame(records).sort_values('Session_ID').reset_index(drop=True)
    result['Order'] = np.arange(1, len(result) + 1)
    return result


def plot_figure(participant, data, cv_y_max, output_path):
    x = data['Order'].to_numpy()
    fig, ax = plt.subplots(figsize=(6, 5), dpi=300)
    ax.plot(x, data['Accuracy'], 'o-', color='#2ca02c', linewidth=2,
            markersize=5, label='Stacking Accuracy (%)')
    ax.set_ylabel('Stacking Accuracy (%)', color='#2ca02c', fontweight='bold')
    ax.set_ylim(0, 105)

    ax_right = ax.twinx()
    ax_right.bar(x, data['CV'], color='dimgray', alpha=0.6,
                 width=0.55, label='CV (%)')
    ax_right.set_ylabel('CV (%)', color='dimgray', fontweight='bold')
    ax_right.set_ylim(0, cv_y_max)

    ax.set_xlim(0.5, len(data) + 0.5)
    ax.set_xlabel('Cumulative Game-Run Number', fontweight='bold')
    ax.xaxis.set_major_locator(MaxNLocator(integer=True, nbins=9))
    ax.grid(True, alpha=0.3)
    ax.set_axisbelow(True)
    ax.text(0.02, 0.95, f'Participant {participant}', transform=ax.transAxes,
            fontsize=13, fontweight='bold', va='top', ha='left',
            bbox=dict(facecolor='white', edgecolor='none', alpha=0.85))
    lines, labels = ax.get_legend_handles_labels()
    other_lines, other_labels = ax_right.get_legend_handles_labels()
    ax.legend(lines + other_lines, labels + other_labels,
              loc='lower center', bbox_to_anchor=(0.5, 1.05), ncol=2,
              framealpha=1.0, edgecolor='black')
    fig.tight_layout()
    fig.savefig(output_path, dpi=300, bbox_inches='tight')
    plt.close(fig)


def main():
    base_dir = Path(__file__).resolve().parent if '__file__' in globals() else Path.cwd()
    parser = argparse.ArgumentParser()
    parser.add_argument('--data-dir', type=Path, default=base_dir)
    parser.add_argument('--output-dir', type=Path, default=base_dir)
    args, _ = parser.parse_known_args()

    setup_style()
    subjects = {pid: load_game_runs(args.data_dir / f'{pid}_data_train4.csv')
                for pid in PARTICIPANTS}
    cv_values = np.concatenate([data['CV'].dropna().to_numpy() for data in subjects.values()])
    cv_max = float(cv_values.max()) if len(cv_values) else 0
    cv_y_max = max(40, math.ceil(cv_max * 1.12 / 10) * 10)
    args.output_dir.mkdir(parents=True, exist_ok=True)

    for pid, data in subjects.items():
        output = args.output_dir / f'Figure7_PrecisionAlignment_{pid}.png'
        plot_figure(pid, data, cv_y_max, output)
        print(f'Figure 7 {pid}: {len(data)} game runs')
        print(output)


if __name__ == '__main__':
    main()