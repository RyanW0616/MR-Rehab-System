# 4. 執行區塊
# ==========================================
file_mapping = {
    'A001': 'A001_data_train4.csv',
    'A002': 'A002_data_train4.csv',
    'A003': 'A003_data_train4.csv'
}

print("="*50)
print("正在處理已清洗的資料並產出 6 張 MDPI 期刊級圖檔")
print("="*50)

processed_subjects_data = {}
target_hand = '左'

for paper_id, csv_file in file_mapping.items():
    if os.path.exists(csv_file):
        processed_df = process_cleaned_data(csv_file)
        if processed_df is not None and not processed_df.empty:
            processed_subjects_data[paper_id] = processed_df
        else:
            print(f"{paper_id} 無有效資料")
    else:
        print(f"找不到檔案：{csv_file}")

if len(processed_subjects_data) > 0:
    plot_individual_figures(processed_subjects_data, hand=target_hand)
    print("\n所有獨立圖表已匯出完畢，可直接插入 Word 進行排版！")
else:
    print("\n沒有足夠的資料可以繪圖。")